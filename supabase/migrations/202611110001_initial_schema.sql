-- Smart StudyMate hosted database baseline.
-- Supabase Auth owns credentials and sessions; this schema stores app profiles and data.
-- All application data is accessed through the trusted Express API. No client RLS policies
-- are defined here, so direct anon/authenticated Data API access remains denied.

create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null default 'Student',
  email text not null unique,
  department text not null default '',
  batch text not null default '',
  role text not null default 'student' check (role in ('student', 'manager', 'admin')),
  created_at timestamptz not null default now()
);

-- New registrations always receive the student role. Role promotion is an admin-only operation.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (auth_user_id, name, email, department, batch, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), 'Student'),
    lower(new.email),
    coalesce(new.raw_user_meta_data ->> 'department', ''),
    coalesce(new.raw_user_meta_data ->> 'batch', ''),
    'student'
  )
  on conflict (auth_user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

create table if not exists public.friend_requests (
  id bigint generated by default as identity primary key,
  sender_id bigint not null references public.profiles(id) on delete cascade,
  receiver_id bigint not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (sender_id <> receiver_id)
);
create index if not exists friend_requests_receiver_status on public.friend_requests(receiver_id, status);

create table if not exists public.friendships (
  user_a bigint not null references public.profiles(id) on delete cascade,
  user_b bigint not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_a, user_b),
  check (user_a < user_b)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id bigint not null references public.profiles(id) on delete cascade,
  recipient_id bigint not null references public.profiles(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  check (sender_id <> recipient_id)
);
create index if not exists messages_pair_time on public.messages(sender_id, recipient_id, id);
create index if not exists messages_recipient on public.messages(recipient_id, read_at);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id bigint references public.profiles(id) on delete set null,
  action text not null,
  target_user_id bigint references public.profiles(id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_logs_time on public.audit_logs(id desc);

create table if not exists public.course_materials (
  id bigint generated by default as identity primary key,
  title text not null,
  course text not null,
  description text not null default '',
  resource_type text not null default 'Notes',
  created_by bigint not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  title text not null,
  course text not null,
  instructions text not null default '',
  due_date date,
  created_by bigint not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.assignment_submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  student_id bigint not null references public.profiles(id) on delete cascade,
  response text not null,
  submitted_at timestamptz not null default now(),
  unique (assignment_id, student_id)
);

create table if not exists public.quizzes (
  id bigint generated by default as identity primary key,
  title text not null,
  course text not null,
  questions jsonb not null default '[]'::jsonb,
  created_by bigint not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  student_id bigint not null references public.profiles(id) on delete cascade,
  score integer not null check (score >= 0),
  total integer not null check (total >= 0),
  completed_at timestamptz not null default now()
);

create table if not exists public.study_notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null default '',
  created_by bigint not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.study_settings (
  key text primary key,
  value text not null
);

-- The Express API uses a trusted server-side database connection and enforces roles.
-- Direct access through Supabase's client-facing Data API has no policies and is denied.
