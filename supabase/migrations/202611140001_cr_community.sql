-- CR status is assigned by an Admin and is checked by the hosted API.
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS is_cr boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.cr_community_messages (
  id bigint generated by default as identity primary key,
  institution text not null,
  department text not null default '',
  batch text not null default '',
  author_id bigint not null references public.profiles(id) on delete cascade,
  body text not null check (length(body) between 1 and 1200),
  created_at timestamptz not null default now()
);

CREATE INDEX IF NOT EXISTS cr_community_institution_time
  ON public.cr_community_messages (lower(institution), id DESC);
ALTER TABLE public.cr_community_messages ENABLE ROW LEVEL SECURITY;
